/*
Write a trigger to insert the values into the NEWEMP table when the 
records are inserted into the EMP table. 
*/

SET SERVEROUTPUT ON
SET VERIFY OFF
SET FEEDBACK OFF

CREATE OR REPLACE TRIGGER TR_UPDATE
BEFORE INSERT ON EMP
FOR EACH ROW

BEGIN

INSERT INTO NEWEMP ( EMPNO, ENAME, SAL) VALUES (:NEW.EID, :NEW.ENAME, :NEW.BASICSAL);

END;
/

SET SERVEROUTPUT OFF
SET VERIFY ON
SET FEEDBACK ON