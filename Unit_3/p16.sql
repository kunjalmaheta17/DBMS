/*
Write a trigger to insert the existing values of the EMP table into 
NEWEMP table when the record is deleted from EMP table.
*/

SET SERVEROUTPUT ON
SET VERIFY OFF
SET FEEDBACK OFF

CREATE OR REPLACE TRIGGER TR_DELETE
BEFORE DELETE ON EMP
FOR EACH ROW

BEGIN

INSERT INTO NEWEMP ( EMPNO, ENAME, SAL) VALUES (:OLD.EID, :OLD.ENAME, :OLD.BASICSAL);

END;
/

SET SERVEROUTPUT OFF
SET VERIFY ON
SET FEEDBACK ON